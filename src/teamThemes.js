const CUSTOM_THEMES_KEY = 'ipl_custom_themes';

export const getCustomThemes = () => {
  try {
    const raw = localStorage.getItem(CUSTOM_THEMES_KEY);
    return raw ? JSON.parse(raw) : {};
  } catch (e) {
    return {};
  }
};

export const registerCustomTheme = (themeData) => {
  try {
    const existing = getCustomThemes();
    const key = (themeData.short || themeData.name || 'CUSTOM').toUpperCase().replace(/[^A-Z0-9]/g, '');
    const color = themeData.color || '#10b981';
    const accent = themeData.accent || color;
    
    const formatted = {
      name: themeData.name.toUpperCase(),
      short: (themeData.short || key).toUpperCase(),
      username: themeData.username || `${key.toLowerCase()}_owner`,
      color: color,
      accent: accent,
      bgGradient: themeData.bgGradient || `linear-gradient(135deg, ${color} 0%, ${accent} 100%)`,
      glow: `${color}45`,
      bgTint: `${color}12`,
      borderTint: `${color}35`,
      badge: themeData.badge || '🏏',
      tag: themeData.tag || 'New Franchise',
      slogan: themeData.slogan || 'Play To Win',
      stadium: themeData.stadium || 'Home Arena'
    };

    existing[key] = formatted;
    localStorage.setItem(CUSTOM_THEMES_KEY, JSON.stringify(existing));
    return formatted;
  } catch (e) {
    console.error('Error saving custom theme:', e);
    return null;
  }
};

export const getTeamTheme = (user, activeTeam) => {
  if (!user) return TEAM_THEMES.ADMIN;
  if (user.role === 'ADMIN') return TEAM_THEMES.ADMIN;

  const raw = [
    activeTeam?.name,
    activeTeam?.short,
    user?.teamName,
    user?.username
  ].filter(Boolean).join(' ').toUpperCase();

  // Check custom user-registered themes first
  const customThemes = getCustomThemes();
  for (const [key, theme] of Object.entries(customThemes)) {
    if (raw.includes(key) || (theme.name && raw.includes(theme.name.toUpperCase())) || (theme.username && raw.includes(theme.username.toUpperCase()))) {
      return theme;
    }
  }

  if (raw.includes('CHENNAI') || raw.includes('CSK')) return TEAM_THEMES.CSK;
  if (raw.includes('MUMBAI') || raw.includes('MI')) return TEAM_THEMES.MI;
  if (raw.includes('BENGALURU') || raw.includes('BANGALORE') || raw.includes('RCB')) return TEAM_THEMES.RCB;
  if (raw.includes('KOLKATA') || raw.includes('KKR')) return TEAM_THEMES.KKR;
  if (raw.includes('RAJASTHAN') || raw.includes('RR')) return TEAM_THEMES.RR;
  if (raw.includes('HYDERABAD') || raw.includes('SRH') || raw.includes('SUNRISERS')) return TEAM_THEMES.SRH;
  if (raw.includes('DELHI') || raw.includes('DC')) return TEAM_THEMES.DC;
  if (raw.includes('GUJARAT') || raw.includes('GT')) return TEAM_THEMES.GT;
  if (raw.includes('LUCKNOW') || raw.includes('LSG')) return TEAM_THEMES.LSG;
  if (raw.includes('PUNJAB') || raw.includes('PBKS')) return TEAM_THEMES.PBKS;

  return TEAM_THEMES.ADMIN;
};
